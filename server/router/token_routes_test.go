package router

import (
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/QuantumNous/new-api/common"
	"github.com/gin-contrib/sessions"
	"github.com/gin-contrib/sessions/cookie"
	"github.com/gin-gonic/gin"
)

func newTokenRouteTestEngine() *gin.Engine {
	gin.SetMode(gin.TestMode)
	common.RedisEnabled = false

	engine := gin.New()
	engine.Use(sessions.Sessions("session", cookie.NewStore([]byte("token-route-test"))))
	SetApiRouter(engine)
	return engine
}

func TestTokenBulkRevealRouteIsNotRegistered(t *testing.T) {
	engine := newTokenRouteTestEngine()

	request := httptest.NewRequest(http.MethodPost, "/api/token/batch/keys", nil)
	recorder := httptest.NewRecorder()
	engine.ServeHTTP(recorder, request)

	if recorder.Code != http.StatusNotFound {
		t.Fatalf("POST /api/token/batch/keys status = %d, want 404; body=%s", recorder.Code, recorder.Body.String())
	}
}

// A single key can be copied or regenerated by its owner, so these routes
// exist, but never for a caller without a signed-in session.
func TestTokenKeyRoutesRequireASignedInUser(t *testing.T) {
	engine := newTokenRouteTestEngine()

	for _, path := range []string{
		"/api/token/123/key",
		"/api/token/123/regenerate",
	} {
		t.Run(path, func(t *testing.T) {
			request := httptest.NewRequest(http.MethodPost, path, nil)
			recorder := httptest.NewRecorder()

			engine.ServeHTTP(recorder, request)

			if recorder.Code != http.StatusUnauthorized {
				t.Fatalf("POST %s status = %d, want 401; body=%s", path, recorder.Code, recorder.Body.String())
			}
		})
	}
}
